SELECT E.*
FROM EMPLOYEE E
JOIN (
    SELECT EMPNO, INCENTIVE_AMOUNT,
           DENSE_RANK() OVER (ORDER BY INCENTIVE_AMOUNT DESC) AS rnk
    FROM INCENTIVES
    WHERE YEAR(INCENTIVE_DATE)=2019
      AND MONTH(INCENTIVE_DATE)=1
) T ON E.EMPNO = T.EMPNO
WHERE rnk = 2;

