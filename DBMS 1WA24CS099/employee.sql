SELECT E.EMPNO, E.ENAME, E.DEPTNO, D.DLOC AS DEPT_LOCATION,
       A.JOB_ROLE, P.PNO, P.PLOC AS PROJECT_LOCATION
FROM EMPLOYEE22 E
JOIN DEPT D ON E.DEPTNO = D.DEPTNO
JOIN ASSIGNED_TO A ON E.EMPNO = A.EMPNO
 JOIN PROJECT P ON A.PNO = P.PNO
WHERE D.DLOC = P.PLOC;

  -- iii List managers with maximum employees
SELECT M.ENAME AS Manager_Name
FROM EMPLOYEE22 M
JOIN EMPLOYEE22 E ON M.EMPNO = E.MGR_NO
GROUP BY M.EMPNO, M.ENAME
HAVING COUNT(E.EMPNO) = (
    SELECT MAX(emp_count)
    FROM (
        SELECT MGR_NO, COUNT(*) AS emp_count
        FROM EMPLOYEE22
        WHERE MGR_NO IS NOT NULL
        GROUP BY MGR_NO
    ) AS t
);

-- iv Managers whose salary > average salary of their employees
SELECT M.ENAME AS Manager_Name, M.SAL
FROM EMPLOYEE M
JOIN EMPLOYEE E ON M.EMPNO = E.MGR_NO
GROUP BY M.EMPNO, M.ENAME, M.SAL
HAVING M.SAL > AVG(E.SAL);

